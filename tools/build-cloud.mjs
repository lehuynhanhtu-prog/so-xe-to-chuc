import {build} from 'esbuild';
import {readFile,writeFile,mkdir,copyFile} from 'node:fs/promises';
await mkdir('apps-script-cloud/vendor',{recursive:true});
await build({entryPoints:['tools/cloud-core-entry.mjs'],bundle:true,outfile:'apps-script-cloud/Core.gs',format:'iife',globalName:'LedgerCore',platform:'neutral',target:'es2020',minify:false,plugins:[{name:'server-crypto-boundary',setup(b){b.onResolve({filter:/^\.\/crypto\.mjs$/},()=>({path:'crypto',namespace:'server-stub'}));b.onLoad({filter:/.*/,namespace:'server-stub'},()=>({contents:'export const randomKey=()=>{},seal=()=>{},open=()=>{},lock=()=>{},unlock=()=>{},strongPassword=()=>{};'}));}}]});
await copyFile('apps-script/Crypto.gs','apps-script-cloud/Crypto.gs');
for(const p of ['ciphers','hashes'])await copyFile('node_modules/@noble/'+p+'/LICENSE','apps-script-cloud/vendor/noble-'+p+'-LICENSE');
let html=await readFile('web/cloud.html','utf8');
const match=html.match(/<script type="module">([\s\S]*?)<\/script>/);
if(!match)throw new Error('Missing cloud UI module');
const result=await build({stdin:{contents:match[1],resolveDir:process.cwd()+'/web',sourcefile:'cloud-ui.mjs'},bundle:true,write:false,format:'iife',target:'es2020',minify:false});
const safe=s=>s.replace(/<\/script/gi,'<\\/script');
html=html.replace(match[0],'<script>'+safe(result.outputFiles[0].text)+'</script>');
html=html.replace('<script src="jszip.min.js"></script>','<script>'+safe(await readFile('web/jszip.min.js','utf8'))+'</script>');
html=html.replace(/<link[^>]+(?:href="(?:manifest\.webmanifest|icons\/[^\"]+)")[^>]*>/g,'');
if(/<script[^>]+src=|<script type="module"/.test(html))throw new Error('Apps Script UI must be self-contained');
await writeFile('apps-script-cloud/Index.html',html);
await copyFile('web/cloud-config.js','docs/cloud-config.js');
await copyFile('web/index.html','docs/index.html');
console.log('Single-owner Apps Script service and self-contained UI built.');
